    pages_dir = r"c:\Users\User\Downloads\日本帝國港灣統計_0001\pages_gamma_strong"
    intermediate_dir = r"c:\Users\User\Downloads\日本帝國港灣統計_0001\intermediate_md_strong"
    final_output_file = r"c:\Users\User\Downloads\日本帝國港灣統計_0001\Full_Output_Strong.md"
    
    if not os.path.exists(intermediate_dir):
        os.makedirs(intermediate_dir)
    
    # Get all page files
    files = sorted([f for f in os.listdir(pages_dir) if f.lower().endswith('.png')])
    
    # Map filenames to page numbers (assuming page_XXX.png)
    page_tasks = []
    
    for f in files:
        # Filter out debug images
        if f.startswith('debug_') or f.startswith('table_') or 'debug' in f:
            continue
            
        try:
            num_str = f.split('_')[-1].split('.')[0]
            num = int(num_str)
            page_tasks.append((num, os.path.join(pages_dir, f), intermediate_dir))
        except:
            continue
            
    # Sort by page number
    page_tasks.sort(key=lambda x: x[0])
    
    print(f"Starting robust batch processing for {len(page_tasks)} pages...")
    
    max_workers = 4 
    
    count = 0 
    total = len(page_tasks)
    
    with concurrent.futures.ThreadPoolExecutor(max_workers=max_workers) as executor:
        futures = {executor.submit(process_and_save_page, task): task for task in page_tasks}
        
        for future in concurrent.futures.as_completed(futures):
            try:
                p_num, status, dur = future.result()
                count += 1
                if status == "Skipped":
                    # Don't spam unless needed, or just print progress
                    if count % 10 == 0:
                        print(f"[{count}/{total}] Skipped existing pages...")
                else:
                    print(f"[{count}/{total}] Page {p_num} {status} in {dur:.2f}s")
            except Exception as e:
                print(f"Worker failed: {e}")

    print("Processing complete. Combining results...")
    combine_results(intermediate_dir, final_output_file)
