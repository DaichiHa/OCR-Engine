"""
Robust Batch Processor for "日本帝國港灣統計"
Supports incremental saving and resuming.
"""

import os
import hybrid_extractor
import concurrent.futures
import time
import glob

def process_and_save_page(page_info):
    """
    Process one page and save immediately to Markdown file.
    """
    page_num, image_path, output_dir = page_info
    md_filename = os.path.join(output_dir, f"page_{page_num:03d}.md")
    
    # Check simple existence for resume
    if os.path.exists(md_filename):
        # Also check if non-empty
        if os.path.getsize(md_filename) > 10:
            return page_num, "Skipped", 0

    try:
        start_time = time.time()
        
        if 1 <= page_num <= 6:
            # Text Mode
            content = hybrid_extractor.extract_vertical_text(image_path)
            # Wrap in minimal markdown
            result = f"\n\n## Page {page_num}\n\n{content}\n"
            
        else:
            # Table Mode
            rows = hybrid_extractor.extract_table_content(image_path)
            if not rows:
                result = f"\n\n## Page {page_num}\n\n(No table data detected)\n"
            else:
                lines = []
                lines.append(f"\n\n## Page {page_num}")
                # Construct Markdown Table
                for row_idx, row in enumerate(rows):
                    # Clean up: Replace pipes with generic separator or escape them
                    clean_row = [str(c).replace('|', '') for c in row if c is not None]
                    lines.append("| " + " | ".join(clean_row) + " |")
                result = "\n".join(lines)
        
        # Save immediately
        if not os.path.exists(output_dir):
            os.makedirs(output_dir, exist_ok=True)
            
        with open(md_filename, 'w', encoding='utf-8') as f:
            f.write(result)
            
        elapsed = time.time() - start_time
        return page_num, "Processed", elapsed
        
    except Exception as e:
        error_msg = f"\n## Page {page_num}\nError: {str(e)}\n"
        with open(md_filename, 'w', encoding='utf-8') as f:
            f.write(error_msg)
        return page_num, f"Error: {str(e)}", 0

def combine_results(intermediate_dir, final_output_file):
    """
    Combine all page_XXX.md files into one.
    """
    # Glob returns string paths
    files = glob.glob(os.path.join(intermediate_dir, "page_*.md"))
    # Sort files naturally
    files.sort()
    
    with open(final_output_file, 'w', encoding='utf-8') as outfile:
        outfile.write("# 日本帝國港灣統計 OCR Result\n\nGenerated by Hybrid Structure-Aware OCR (Robust Batch)\n\n")
        
        for md_file in files:
            with open(md_file, 'r', encoding='utf-8') as infile:
                content = infile.read()
                outfile.write(content)
                outfile.write("\n\n---\n\n")
    
    print(f"Combined {len(files)} pages into {final_output_file}")

